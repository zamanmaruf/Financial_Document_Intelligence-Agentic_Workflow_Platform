"""Build the extraction fine-tuning dataset in evals/finetune/.

    python scripts/finetune/build_dataset.py [--seed 20261006] [--prompt-version 1.2.0]

Generates the seeded synthetic corpus (app/finetune/corpus.py), renders each document to PDF
and reads it back with the production pypdf extractor, builds a chat record from the production
extraction prompt, and replays every answer through the real extraction service. It stops
without writing anything if any record would not be accepted. Offline and deterministic.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections import Counter
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "scripts"))

from generate_sample_data import render_text_pdf  # noqa: E402

from app.extraction.service import PROMPT_NAME  # noqa: E402
from app.finetune.corpus import DEFAULT_SEED, SPLITS, generate_corpus, stem_of  # noqa: E402
from app.finetune.records import check_target, target_output, training_record  # noqa: E402
from app.ingestion.pdf import PypdfTextExtractor  # noqa: E402
from app.prompts.registry import PromptRegistry  # noqa: E402

OUT = ROOT / "evals" / "finetune"


def _jsonl(rows: list[dict[str, Any]]) -> bytes:
    return "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in rows).encode("utf-8")


def _data_card(manifest: dict[str, Any]) -> str:
    counts = manifest["counts"]
    rows = "\n".join(
        f"| {t} | {counts['train'].get(t, 0)} | {counts['validation'].get(t, 0)} | "
        f"{counts['test'].get(t, 0)} |"
        for t in sorted(counts["train"])
    )
    traits = "\n".join(f"| {k} | {v} |" for k, v in sorted(manifest["traits"].items()))
    return f"""# Data card: extraction fine-tuning set

Generated by `scripts/finetune/build_dataset.py` (seed {manifest["seed"]}) from
`app/finetune/corpus.py`. Everything here is synthetic: the companies, people, banks, funds and
figures are invented, and no real customer data was used. Regenerating with the same seed and
prompt version reproduces these files byte for byte (hashes in `manifest.json`).

**Task.** Extract the typed fields for one of five document types (income statement, balance
sheet, invoice, bank statement, fund summary), with the value as printed, the verbatim
evidence line, the page and a confidence, in the JSON shape the extraction service validates.

**Input.** The production prompt `{manifest["prompt"]["name"]}@{manifest["prompt"]["version"]}`
(hash `{manifest["prompt"]["hash"]}`), rendered over text that pypdf extracted from a rendered
PDF, as in production.

**Target.** The expected answer. Every record was replayed through the production
`EntityExtractor` and kept only if it recovered every expected value with verified evidence.

**Splits.** Each document type has seven layout families (label wording, line layout, number
format, sign convention, heading style). Four families are for training, one for validation and
two for test, so the test set is made of layouts the model never saw. Name stems are also split,
so no company, bank, fund or person name appears in more than one split.

| Document type | Train | Validation | Test |
|---|---|---|---|
{rows}

| Trait (documents) | Count |
|---|---|
{traits}

**Limits.** Synthetic, single-column, digitally generated text in a fixed-width font. No scans,
handwriting, multi-column layouts or real-world noise. Results on this set say how well a model
learns these layouts, not how it will do on real documents.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--prompt-version", default=None, help="default: the active version")
    parser.add_argument("--out", type=Path, default=OUT)
    args = parser.parse_args()

    registry = PromptRegistry.load(ROOT / "prompts")
    version = args.prompt_version or registry.active_versions()[PROMPT_NAME]
    prompt = registry.get(PROMPT_NAME, version)
    extractor = PypdfTextExtractor()

    documents: list[dict[str, Any]] = []
    records: dict[str, list[dict[str, Any]]] = {"train": [], "validation": []}
    problems: list[str] = []
    docs = generate_corpus(args.seed)
    for doc in docs:
        text = extractor.extract(render_text_pdf(doc.pages))
        target = target_output(doc, text)
        record = training_record(registry, version, doc.document_type, text, target)
        answer = record["messages"][-1]["content"]
        found = check_target(registry, version, doc.document_type, text, answer, doc.expected())
        problems.extend(f"{doc.doc_id}: {p}" for p in found)
        documents.append(
            {
                "doc_id": doc.doc_id,
                "split": doc.split,
                "document_type": doc.document_type.value,
                "family": doc.family,
                "entity": doc.entity,
                "traits": doc.traits,
                "pages": [p.text for p in text.pages],
                "expected": doc.expected(),
            }
        )
        if doc.split in records:
            records[doc.split].append(record)
    if problems:
        print("\n".join(problems[:50]))
        print(f"{len(problems)} problems; nothing written")
        return 1

    files = {
        "documents.jsonl": _jsonl(documents),
        "train.jsonl": _jsonl(records["train"]),
        "validation.jsonl": _jsonl(records["validation"]),
    }
    counts: dict[str, dict[str, int]] = {s: {} for s in SPLITS}
    for d in documents:
        counts[d["split"]][d["document_type"]] = counts[d["split"]].get(d["document_type"], 0) + 1
    manifest = {
        "seed": args.seed,
        "generator": "app/finetune/corpus.py",
        "prompt": {"name": PROMPT_NAME, "version": version, "hash": prompt.hash},
        "counts": counts,
        "families": {s: sorted({d.family for d in docs if d.split == s}) for s in SPLITS},
        "name_stems": {
            s: sorted({stem_of(n).title() for d in docs if d.split == s for n in d.names})
            for s in SPLITS
        },
        "traits": dict(Counter(t for d in docs for t in d.traits)),
        "files": {
            name: {
                "sha256": hashlib.sha256(data).hexdigest(),
                "lines": data.count(b"\n"),
                "bytes": len(data),
            }
            for name, data in files.items()
        },
    }
    args.out.mkdir(parents=True, exist_ok=True)
    for name, data in files.items():
        (args.out / name).write_bytes(data)
    (args.out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    (args.out / "DATA_CARD.md").write_text(_data_card(manifest))
    print(
        f"{len(docs)} documents: "
        + ", ".join(f"{s} {sum(counts[s].values())}" for s in SPLITS)
        + f"; prompt {PROMPT_NAME}@{version}; written to {args.out.relative_to(ROOT)}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
