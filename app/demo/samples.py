_BY_ID = {s.sample_id: s for s in SAMPLES}


def get_sample(sample_id: str) -> DemoSample:
    sample = _BY_ID.get(sample_id)
    if sample is None:
        raise SampleNotFoundError(f"unknown sample '{sample_id}'")
    return sample


def sample_bytes(sample: DemoSample, sample_dir: Path) -> bytes:
    path = (sample_dir / "pdfs" / sample.filename).resolve()
    if not path.is_file():
        raise SampleNotFoundError(f"sample file for '{sample.sample_id}' is not installed")
    return path.read_bytes()
