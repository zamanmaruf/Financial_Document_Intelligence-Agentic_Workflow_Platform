"""Allow-listed synthetic sample documents for the public demo.

Visitors can only load these files by id; no client-supplied path ever reaches the filesystem.
All samples are synthetic (generated by ``scripts/generate_sample_data.py``).
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from app.core.errors import NotFoundError


class SampleNotFoundError(NotFoundError):
    error_type = "sample_not_found"


@dataclass(frozen=True)
class DemoSample:
    sample_id: str
    filename: str
    title: str
    document_kind: str
    summary: str
    expected_outcome: str  # READY | NEEDS_REVIEW
    lesson: str
    suggested_questions: tuple[str, ...]


